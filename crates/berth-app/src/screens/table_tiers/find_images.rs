//! The Find images results table's column-drop tiers (P4-T3).
//!
//! The table sits left of the 420 px detail panel, so its room is the
//! screen's width minus the panel (`panel_width`, the same rule as the
//! stylesheet's). It drops Updated first, then Pulls, then Stars, then
//! Publisher; Name and Platforms stay (the amd64 note matters most).

use std::fmt::Write as _;

use super::{scoped, threshold, write_or_check, Table, View};
use crate::screens::css_tracks as css;
use crate::text_scale::STEPS;

const FIND_HAND: &str = include_str!("../../../assets/css/find_images.css");

const FIND_FILE: &str = concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/assets/css/find_images_tiers.css"
);

/// A column the results table drops as it narrows.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum FindCol {
    Updated,
    Pulls,
    Stars,
    Publisher,
}

impl FindCol {
    /// The cell class and the header cell (the header's children are in
    /// column order: Name, Publisher, Stars, Pulls, Updated, Platforms).
    fn selectors(self) -> &'static [&'static str] {
        match self {
            Self::Updated => &[".fi-updated", ".fi-head > :nth-child(5)"],
            Self::Pulls => &[".fi-pulls", ".fi-head > :nth-child(4)"],
            Self::Stars => &[".fi-stars", ".fi-head > :nth-child(3)"],
            Self::Publisher => &[".fi-publisher", ".fi-head > :nth-child(2)"],
        }
    }
}

/// The lists the table steps through as it narrows, widest first.
pub fn find_steps() -> Vec<(String, Vec<FindCol>)> {
    let body = css::block(FIND_HAND, "\n.fi-table {");
    let list = |name: &str| css::declaration(body, name);
    vec![
        (list("--fi-cols"), vec![]),
        (list("--fi-cols-no-updated"), vec![FindCol::Updated]),
        (
            list("--fi-cols-no-pulls"),
            vec![FindCol::Updated, FindCol::Pulls],
        ),
        (
            list("--fi-cols-no-stars"),
            vec![FindCol::Updated, FindCol::Pulls, FindCol::Stars],
        ),
        (
            list("--fi-cols-compact"),
            vec![
                FindCol::Updated,
                FindCol::Pulls,
                FindCol::Stars,
                FindCol::Publisher,
            ],
        ),
    ]
}

/// The room a list asks for: its tracks' minimums, the 12 px gaps and the
/// page gutter on both sides.
fn find_need(cols: &str, scale: f32, view: View) -> f32 {
    let tracks = css::tracks(cols);
    css::min_sum(&tracks, scale) + 12.0 * (tracks.len() as f32 - 1.0) + 2.0 * view.gutter()
}

/// The panel's width beside a `body` px wide results area (the stylesheet's
/// `clamp(300px, 100cqw - 150px - 168px * scale - 52px, 420px)`): 420 when
/// the table keeps what the compact list needs, less when it does not.
#[must_use]
pub fn panel_width(body: f32, scale: f32) -> f32 {
    (body - 150.0 - 168.0 * scale - 52.0).clamp(300.0, 420.0)
}

/// The list in force for a results table `width` px wide.
#[derive(Debug, Clone, PartialEq)]
pub struct FindState {
    pub tracks: Vec<String>,
    pub hidden: Vec<FindCol>,
    pub step: usize,
}

pub fn find_state_at(view: View, width: f32, scale: f32) -> FindState {
    let steps = find_steps();
    let mut index = 0;
    while index + 1 < steps.len() && width <= threshold(find_need(&steps[index].0, scale, view)) as f32
    {
        index += 1;
    }
    FindState {
        tracks: css::tracks(&steps[index].0),
        hidden: steps[index].1.clone(),
        step: index,
    }
}

fn find_css() -> String {
    let steps = find_steps();
    let mut out = String::from(
        "/* Generated by screens/table_tiers/find_images.rs from the track lists in find_images.css.\n   \
         Never edit by hand: BERTH_REGEN_TIERS=1 cargo nextest run -p berth-app table_tiers.\n\n   \
         Each rule leaves a list at the exact width its tracks stop fitting (the sum of\n   \
         their minimums, the 12 px gaps and both page gutters) for one text size. */\n",
    );
    for view in [View::Narrow, View::Wide] {
        let _ = writeln!(out, "\n@media {} {{", view.media());
        for scale in STEPS {
            let _ = writeln!(out, "  /* text size {scale} */");
            for window in steps.windows(2) {
                let at = threshold(find_need(&window[0].0, scale, view));
                let (cols, hide) = &window[1];
                let _ = writeln!(out, "  @container findtable (max-width: {at}px) {{");
                let _ = writeln!(
                    out,
                    "    {} {{\n      --fi-cols: {cols};\n    }}",
                    scoped(scale, ".fi-table")
                );
                let hidden: Vec<String> = hide
                    .iter()
                    .flat_map(|col| col.selectors())
                    .map(|sel| format!(".fi-table {sel}"))
                    .collect();
                if !hidden.is_empty() {
                    let _ = writeln!(
                        out,
                        "    {} {{\n      display: none;\n    }}",
                        scoped(scale, &hidden.join(", "))
                    );
                }
                out.push_str("  }\n");
            }
        }
        out.push_str("}\n");
    }
    out
}

pub(super) const TABLE: Table = Table {
    name: "find_images",
    file: FIND_FILE,
    css: find_css,
    needs: find_needs,
};

fn find_needs(view: View, scale: f32) -> Vec<Vec<f32>> {
    vec![find_steps()
        .iter()
        .map(|(cols, _)| find_need(cols, scale, view))
        .collect()]
}

#[test]
fn table_tiers_find_images_stylesheet_is_the_generator_output() {
    write_or_check(FIND_FILE, &find_css());
}

#[test]
fn table_tiers_find_images_thresholds_fall_and_name_every_text_size() {
    for view in [View::Narrow, View::Wide] {
        for scale in STEPS {
            let needs: Vec<f32> = find_steps()
                .iter()
                .map(|(cols, _)| find_need(cols, scale, view))
                .collect();
            assert!(
                needs.windows(2).all(|w| w[0] > w[1]),
                "find {view:?} {scale}: {needs:?}"
            );
        }
    }
    let css = find_css();
    assert!(css.contains(":root:not([data-text-scale])"));
    for scale in STEPS {
        if scale != 1.0 {
            assert!(
                css.contains(&format!("[data-text-scale=\"{scale}\"]")),
                "{scale}"
            );
        }
    }
}
