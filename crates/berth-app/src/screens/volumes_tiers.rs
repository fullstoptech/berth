//! The column-drop tiers of the Volumes table, generated (P4-T4).
//!
//! The Volumes table drops Driver first, then Created, then Project as its
//! container narrows (Name, Size, Used by and the row buttons stay). The
//! full track list is hand-written in `volumes.css`; every narrower list is
//! that list with the hidden columns' tracks removed, so the two cannot
//! disagree. Each rule leaves a list at the exact width its tracks stop
//! fitting (the sum of their minimums, the 12 px gaps and both page
//! gutters), for every text size, scoped by `data-text-scale` like the
//! Containers and Projects tiers (`table_tiers.rs`, whose helpers this reuses).
//! The output is `assets/css/volumes_tiers.css`, checked in; the tests fail
//! when it is stale. Regenerate with
//!
//! ```text
//! BERTH_REGEN_TIERS=1 cargo nextest run -p berth-app volumes_tiers
//! ```

use std::fmt::Write as _;

use super::css_tracks as css;
use super::table_tiers::{scoped, threshold, write_or_check, View};
use crate::text_scale::STEPS;

const HAND: &str = include_str!("../../assets/css/volumes.css");
const FILE: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/assets/css/volumes_tiers.css");

/// A column a tier hides, in the order they go.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Col {
    Driver,
    Created,
    Project,
}

impl Col {
    /// Where the column's track sits in the full list: name, project, size,
    /// used by, driver, created, buttons.
    fn track(self) -> usize {
        match self {
            Self::Project => 1,
            Self::Driver => 4,
            Self::Created => 5,
        }
    }

    fn selectors(self) -> [&'static str; 2] {
        match self {
            Self::Driver => [".vl-table .vl-driver", ".vl-table .vl-driver-head"],
            Self::Created => [".vl-table .vl-created", ".vl-table .vl-created-head"],
            Self::Project => [".vl-table .vl-project", ".vl-table .vl-project-head"],
        }
    }
}

/// The tiers, widest first: the columns each one has hidden.
pub const TIERS: [&[Col]; 4] = [
    &[],
    &[Col::Driver],
    &[Col::Driver, Col::Created],
    &[Col::Driver, Col::Created, Col::Project],
];

/// The full list, read from the hand-written stylesheet.
fn full_list() -> Vec<String> {
    css::tracks(&css::declaration(
        css::block(HAND, "\n.vl-table {"),
        "--vl-cols",
    ))
}

/// The track list with `hidden` columns removed.
pub fn tracks_for(hidden: &[Col]) -> Vec<String> {
    let gone: Vec<usize> = hidden.iter().map(|c| c.track()).collect();
    full_list()
        .into_iter()
        .enumerate()
        .filter(|(i, _)| !gone.contains(i))
        .map(|(_, t)| t)
        .collect()
}

/// The room a tier asks for: its tracks' minimums, the 12 px gaps and the
/// page gutter on both sides.
pub fn need(tier: usize, scale: f32, view: View) -> f32 {
    let tracks = tracks_for(TIERS[tier]);
    css::min_sum(&tracks, scale) + 12.0 * (tracks.len() as f32 - 1.0) + 2.0 * view.gutter()
}

/// The tier in force for a table `width` px wide.
pub fn tier_at(view: View, width: f32, scale: f32) -> usize {
    let mut tier = 0;
    while tier + 1 < TIERS.len() && width <= threshold(need(tier, scale, view)) as f32 {
        tier += 1;
    }
    tier
}

/// The least room the narrowest tier needs.
pub fn least_need(view: View, scale: f32) -> f32 {
    need(TIERS.len() - 1, scale, view)
}

fn volumes_css() -> String {
    let mut out = String::from(
        "/* Generated by screens/volumes_tiers.rs from the track list in volumes.css.\n   \
         Never edit by hand: BERTH_REGEN_TIERS=1 cargo nextest run -p berth-app volumes_tiers.\n\n   \
         Each rule leaves a list at the exact width its tracks stop fitting (the sum of\n   \
         their minimums, the 12 px gaps and both page gutters) for one text size: Driver\n   \
         goes first, then Created, then Project. */\n",
    );
    for view in [View::Narrow, View::Wide] {
        let _ = writeln!(out, "\n@media {} {{", view.media());
        for scale in STEPS {
            let _ = writeln!(out, "  /* text size {scale} */");
            for tier in 0..TIERS.len() - 1 {
                let at = threshold(need(tier, scale, view));
                let next = TIERS[tier + 1];
                let _ = writeln!(out, "  @container volumes (max-width: {at}px) {{");
                let _ = writeln!(
                    out,
                    "    {} {{\n      --vl-cols: {};\n    }}",
                    scoped(scale, ".vl-table"),
                    tracks_for(next).join(" ")
                );
                let hidden: Vec<&str> = next.iter().flat_map(|c| c.selectors()).collect();
                let _ = writeln!(
                    out,
                    "    {} {{\n      display: none;\n    }}",
                    scoped(scale, &hidden.join(", "))
                );
                out.push_str("  }\n");
            }
        }
        out.push_str("}\n");
    }
    out
}

#[test]
fn volumes_tiers_stylesheet_is_the_generator_output() {
    write_or_check(FILE, &volumes_css());
}

#[test]
fn volumes_tiers_thresholds_fall_as_the_lists_narrow() {
    for view in [View::Narrow, View::Wide] {
        for scale in STEPS {
            let needs: Vec<f32> = (0..TIERS.len()).map(|t| need(t, scale, view)).collect();
            assert!(
                needs.windows(2).all(|w| w[0] > w[1]),
                "{view:?} {scale}: {needs:?}"
            );
        }
    }
}

#[test]
fn volumes_tiers_every_data_track_scales_with_the_text_size() {
    // Name, Project, Used by flex on their own minimums; Size, Driver,
    // Created and the buttons hold text or icons and grow with the text.
    let full = full_list();
    assert_eq!(full.len(), 7, "{full:?}");
    for index in [2, 4, 5, 6] {
        assert!(
            css::has_scale(&full[index]),
            "track {index} `{}`",
            full[index]
        );
    }
}

#[test]
fn volumes_tiers_drop_driver_then_created_then_project() {
    assert_eq!(tracks_for(TIERS[0]).len(), 7);
    assert_eq!(tracks_for(TIERS[1]).len(), 6);
    assert_eq!(tracks_for(TIERS[2]).len(), 5);
    assert_eq!(tracks_for(TIERS[3]).len(), 4);
    // The buttons' track is always the last one.
    assert_eq!(tracks_for(TIERS[3]).last(), full_list().last());
    // The first tier is what the stylesheet draws when everything fits: no
    // rule is in force at the widths the full list fits.
    for view in [View::Narrow, View::Wide] {
        let wide = need(0, 1.0, view) + 1.0;
        assert_eq!(tier_at(view, wide, 1.0), 0);
        assert_eq!(tier_at(view, wide - 10.0, 1.0), 1);
    }
}

/// The table's width next to the inspector at `stored` px in a `window` px
/// wide window at `scale` text (D21, D24): docked (clamped to keep the main
/// area at 640 px x scale, from 1200 px up and when 320 px of it fit) or
/// else the whole main area.
fn table_width(window: f32, stored: u32, scale: f32) -> (f32, bool) {
    match crate::ui::dock::docked_width(f64::from(window), stored, scale) {
        Some(width) => (window - 220.0 - width as f32, true),
        None => (window - 220.0, false),
    }
}

fn assert_fits(width: f32, view: View, scale: f32) {
    let tier = tier_at(view, width, scale);
    let tracks = tracks_for(TIERS[tier]);
    let used =
        css::min_sum(&tracks, scale) + 12.0 * (tracks.len() as f32 - 1.0) + 2.0 * view.gutter();
    assert!(
        used <= width + 0.5,
        "{width} px at {scale} ({view:?}): tier {tier} needs {used} ({tracks:?})"
    );
}

#[test]
fn volumes_table_fits_every_window_inspector_width_and_text_size() {
    // The D24 sweep: windows 1024 / 1220 / 1440, inspector widths 320 / 360 /
    // 480 / 560, every text size.
    let mut docked_cases = 0;
    for window in [1024.0, 1220.0, 1440.0] {
        let view = if window < 1200.0 {
            View::Narrow
        } else {
            View::Wide
        };
        for stored in [320, 360, 480, 560] {
            for scale in STEPS {
                let (width, docked) = table_width(window, stored, scale);
                docked_cases += usize::from(docked);
                assert_fits(width, view, scale);
            }
        }
    }
    assert!(docked_cases > 30, "{docked_cases} docked cases");
}

#[test]
fn volumes_table_fits_the_main_area_floor_at_every_text_size() {
    for scale in STEPS {
        let floor = crate::ui::dock::main_min_px(scale) as f32;
        assert_fits(floor, View::Wide, scale);
        assert!(
            least_need(View::Wide, scale) <= floor,
            "{scale}: the narrowest list needs {} px, the floor is {floor}",
            least_need(View::Wide, scale)
        );
    }
}

#[test]
fn volumes_table_fits_every_width_from_its_narrowest_list_up() {
    for view in [View::Narrow, View::Wide] {
        for scale in STEPS {
            let floor = least_need(view, scale).ceil() as u32;
            for width in (floor..1500).step_by(3) {
                assert_fits(width as f32, view, scale);
            }
        }
    }
}

#[test]
fn volumes_tiers_attribute_values_are_the_ones_the_page_sets() {
    let css_text = volumes_css();
    for scale in STEPS {
        let key = format!("[data-text-scale=\"{scale}\"]");
        assert!(css_text.contains(&key), "{scale}");
        if (scale - 1.0).abs() < f32::EPSILON {
            assert!(css_text.contains(":root:not([data-text-scale])"));
        }
    }
}
