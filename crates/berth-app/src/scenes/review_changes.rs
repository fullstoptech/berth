/// "Review changes / default / 1440": Claude Code moves Postgres to 5433 and makes the worker wait
/// for it; two files change, the volume is kept.
pub(crate) fn shop_api_plan() -> PendingPlan {
    let root = berth_sys::paths::home().join("Dev/clients/acme/shop-api");
    let plan = GenerationPlan {
        root: root.clone(),
        files: vec![
            diff("compose.yaml", Some(SHOP_COMPOSE_OLD), SHOP_COMPOSE_NEW),
            diff(".env", Some(SHOP_ENV_OLD), SHOP_ENV_NEW),
        ],
        source: PlanSource::Harness(HarnessId("claude".to_string())),
        notes: Vec::new(),
        after_write: Some(ComposeCommand::Up {
            services: vec!["db".to_string(), "worker".to_string()],
            build: false,
        }),
    };
    let mut pending = PendingPlan::new(plan, "shop-api");
    pending.run = Some(PlanRun::for_folder(
        &engine(),
        &root,
        vec![PathBuf::from("compose.yaml")],
    ));
    pending.footer_note = Some("Volume shop-api_pgdata (1.2 GB) is kept.".to_string());
    pending
}

