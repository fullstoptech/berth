#!/usr/bin/env python3
"""Generate tokens.css from design/tokens.json (PLAN 7.7). Stdlib only.

Usage: python3 -I scripts/gen-tokens.py design/tokens.json > crates/berth-app/assets/css/tokens.css
"""
import json
import sys


def leaves(node):
    return {k: v["$value"] for k, v in node.items() if isinstance(v, dict) and "$value" in v}


def resolve(value, tokens):
    seen = set()
    while isinstance(value, str) and value.startswith("{") and value.endswith("}"):
        ref = value[1:-1]
        if ref in seen:
            raise SystemExit(f"token reference cycle: {ref}")
        seen.add(ref)
        node = tokens
        for part in ref.split("."):
            node = node[part]
        value = node["$value"]
    return value


def scaled(px):
    """A pixel value that grows with the user's text size (--text-scale, set on <html>)."""
    assert px.endswith("px"), px
    return f"calc({px} * var(--text-scale, 1))"


def scaled_whole(px):
    """Like scaled, rounded to whole pixels: the virtual table's row maths in Rust
    (text_scale::scaled_px) must agree with the CSS row height to the pixel."""
    return f"round({scaled(px)}, 1px)"


def main():
    tokens = json.load(open(sys.argv[1]))
    out = ["/* Generated by scripts/gen-tokens.py from design/tokens.json. Never edit by hand. */"]

    def color_block(roles, indent="  "):
        return [f"{indent}--color-{name}: {resolve(value, tokens)};" for name, value in roles.items()]

    light_roles = leaves(tokens["color"])
    ramps = {k: v for k, v in tokens["color"].items() if isinstance(v, dict) and "$value" not in v}

    out.append(":root {")
    out += color_block(light_roles)
    for ramp, steps in ramps.items():
        for step, value in leaves(steps).items():
            out.append(f"  --{ramp}-{step}: {resolve(value, tokens)};")
    fam = leaves(tokens["type"]["family"])
    out.append(f"  --font-text: {fam['text']};")
    out.append(f"  --font-mono: {fam['mono']};")
    sizes = leaves(tokens["type"]["size"])
    lines = leaves(tokens["type"]["line-height"])
    weights = leaves(tokens["type"]["weight"])
    for role in sizes:
        out.append(f"  --text-{role}-size: {scaled(sizes[role])};")
        out.append(f"  --text-{role}-line: {scaled(lines[role])};")
        out.append(f"  --text-{role}-weight: {weights[role]};")
    for name, value in leaves(tokens["space"]).items():
        out.append(f"  --space-{name}: {value};")
    for name in ("sm", "md", "lg", "full"):
        out.append(f"  --radius-{name}: {resolve(tokens['radius'][name]['$value'], tokens)};")
    for name in ("sm", "md", "lg"):
        out.append(f"  --size-control-{name}: {scaled(tokens['size']['control'][name]['$value'])};")
    out.append(f"  --size-row: {scaled_whole(tokens['size']['row']['md']['$value'])};")
    for name in ("sm", "md"):
        out.append(f"  --size-icon-{name}: {scaled(tokens['size']['icon'][name]['$value'])};")
    # Fixed on purpose: the title bar keeps the native traffic lights centred; the
    # side panels and spacing keep the layout stable at every text size.
    for name in ("sidebar", "inspector", "titlebar"):
        out.append(f"  --size-{name}: {tokens['size'][name]['$value']};")
    for name in ("popover", "sheet", "dialog"):
        out.append(f"  --shadow-{name}: {tokens['shadow'][name]['$value']};")
    for name, value in leaves(tokens["motion"]["duration"]).items():
        out.append(f"  --motion-{name}: {value};")
    for name, value in leaves(tokens["motion"]["dwell"]).items():
        out.append(f"  --dwell-{name}: {value};")
    out.append(f"  --ease-standard: {tokens['motion']['easing']['standard']['$value']};")
    out.append("}")

    dark_roles = leaves(tokens["dark"]["color"])
    out.append('@media (prefers-color-scheme: dark) {')
    out.append('  :root:not([data-theme="light"]) {')
    out += color_block(dark_roles, indent="    ")
    out.append("  }")
    out.append("}")
    out.append(':root[data-theme="dark"] {')
    out += color_block(dark_roles)
    out.append("}")

    out.append(':root[data-density="compact"] {')
    out.append(f"  --size-row: {scaled_whole(tokens['density']['compact']['size']['row']['md']['$value'])};")
    out.append(f"  --size-control-md: {scaled(tokens['density']['compact']['size']['control']['md']['$value'])};")
    out.append(f"  --space-12: {tokens['density']['compact']['space']['12']['$value']};")
    out.append("}")

    out.append("@media (prefers-reduced-motion: reduce) {")
    out.append("  :root {")
    for name in leaves(tokens["motion"]["duration"]):
        out.append(f"    --motion-{name}: 0ms;")
    out.append("  }")
    out.append("}")

    print("\n".join(out))


if __name__ == "__main__":
    main()
