#!/usr/bin/env python3
"""Build the SVG icon sprite from the FigCraft icon components (PLAN D10, P0-T3).

Finds every `Icon/<name>` component in the .figcraft document, exports each
with figcraft-cli as SVG, and writes one sprite to stdout: one
`<symbol id="<name>">` per icon, strokes and filled glyphs in currentColor,
no hex colours. Stdlib only (figcraft-cli must be on PATH).

Usage: python3 -I scripts/build-icons.py [design/berth.figcraft] > crates/berth-app/assets/icons.svg
"""
import json
import re
import subprocess
import sys
import tempfile
import zipfile
from pathlib import Path


def icon_names(figcraft: Path):
    with zipfile.ZipFile(figcraft) as z:
        document = json.loads(z.read("document.json"))
    nodes = document["nodes"].values()
    icons = [n for n in nodes if n.get("type") == "component" and str(n.get("name", "")).startswith("Icon/")]
    icons.sort(key=lambda n: n["id"])
    return [n["name"][len("Icon/"):] for n in icons]


def export_svg(figcraft: Path, name: str, out_dir: Path) -> str:
    out = out_dir / f"{name}.svg"
    subprocess.run(
        ["figcraft-cli", "export", str(figcraft), "-o", str(out), "--format", "svg",
         "--page", "Components", "--node", f"Icon/{name}"],
        check=True, stdout=subprocess.DEVNULL,
    )
    return out.read_text()


def symbol(name: str, svg: str) -> str:
    view_box = re.search(r'viewBox="([^"]+)"', svg).group(1)
    inner = svg[svg.index(">") + 1:svg.rindex("</svg>")]
    inner = re.sub(r'stroke="#[0-9a-fA-F]+"', 'stroke="currentColor"', inner)
    inner = re.sub(r'fill="#[0-9a-fA-F]+"', 'fill="currentColor"', inner)
    return f'<symbol id="{name}" viewBox="{view_box}" fill="none" stroke="currentColor">{inner}</symbol>'


def main():
    figcraft = Path(sys.argv[1] if len(sys.argv) > 1 else "design/berth.figcraft")
    names = icon_names(figcraft)
    with tempfile.TemporaryDirectory() as tmp:
        symbols = [symbol(name, export_svg(figcraft, name, Path(tmp))) for name in names]
    print("<!-- Generated by scripts/build-icons.py from design/berth.figcraft. Never edit by hand. -->")
    print('<svg xmlns="http://www.w3.org/2000/svg" fill="none" style="display:none">')
    for s in symbols:
        print(s)
    print("</svg>")


if __name__ == "__main__":
    main()
