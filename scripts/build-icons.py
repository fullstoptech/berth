#!/usr/bin/env python3
"""Build the SVG icon sprite from the FigCraft icon components (PLAN D10, P0-T3).

Finds every `Icon/<name>` component in the .figcraft document, exports each
with figcraft-cli as SVG, and writes one sprite to stdout: one
`<symbol id="<name>">` per icon (viewBox = the 16x16 component frame), strokes and filled glyphs in currentColor,
no hex colours. Stdlib only (figcraft-cli must be on PATH).

Usage: python3 -I scripts/build-icons.py [design/berth.figcraft] > crates/berth-app/assets/icons.svg
"""
import json
import re
import subprocess
import sys
import tempfile
import zipfile
from pathlib import Path


def icon_names(figcraft: Path):
    with zipfile.ZipFile(figcraft) as z:
        document = json.loads(z.read("document.json"))
    nodes = document["nodes"]
    icons = [n for n in nodes.values() if n.get("type") == "component" and str(n.get("name", "")).startswith("Icon/")]
    icons.sort(key=lambda n: n["id"])
    return [(n["name"][len("Icon/"):], frame(n, nodes)) for n in icons]


def frame(component, nodes):
    """(width, height, min child x, min child y) of an icon component in its own space."""
    kids = [nodes[str(c)] for c in component["children"]]
    return (
        component["width"],
        component["height"],
        min(k["transform"][4] for k in kids),
        min(k["transform"][5] for k in kids),
    )


def export_svg(figcraft: Path, name: str, out_dir: Path) -> str:
    out = out_dir / f"{name}.svg"
    subprocess.run(
        ["figcraft-cli", "export", str(figcraft), "-o", str(out), "--format", "svg",
         "--page", "Components", "--node", f"Icon/{name}"],
        check=True, stdout=subprocess.DEVNULL,
    )
    return out.read_text()


def view_box(svg: str, box) -> str:
    """The component's own frame (16x16) in the exported SVG's coordinates.

    figcraft-cli crops an export to the glyph plus padding, so the exported
    viewBox is not the component frame: scaled into the icon box the glyphs
    came out at about 0.6 of the frame's size. The exported paths carry the
    children's component-space offsets plus one constant shift; the smallest
    exported offset minus the smallest child offset is the frame's origin.
    """
    width, height, kid_x, kid_y = box
    offsets = [tuple(map(float, m.split())) for m in re.findall(r"matrix\(([^)]+)\)", svg)]
    origin_x = min(o[4] for o in offsets) - kid_x
    origin_y = min(o[5] for o in offsets) - kid_y
    return " ".join(f"{round(v, 3) + 0.0:.3f}".rstrip("0").rstrip(".") or "0" for v in (origin_x, origin_y, width, height))


def symbol(name: str, svg: str, box) -> str:
    view_box_attr = view_box(svg, box)
    inner = svg[svg.index(">") + 1:svg.rindex("</svg>")]
    inner = re.sub(r'stroke="#[0-9a-fA-F]+"', 'stroke="currentColor"', inner)
    inner = re.sub(r'fill="#[0-9a-fA-F]+"', 'fill="currentColor"', inner)
    return f'<symbol id="{name}" viewBox="{view_box_attr}" fill="none" stroke="currentColor">{inner}</symbol>'


def main():
    figcraft = Path(sys.argv[1] if len(sys.argv) > 1 else "design/berth.figcraft")
    names = icon_names(figcraft)
    with tempfile.TemporaryDirectory() as tmp:
        symbols = [symbol(name, export_svg(figcraft, name, Path(tmp)), box) for name, box in names]
    print("<!-- Generated by scripts/build-icons.py from design/berth.figcraft. Never edit by hand. -->")
    print('<svg xmlns="http://www.w3.org/2000/svg" fill="none" style="display:none">')
    for s in symbols:
        print(s)
    print("</svg>")


if __name__ == "__main__":
    main()
